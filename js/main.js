function element(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text) node.textContent = text;
  return node;
}
// Cache README responses across filter changes to avoid repeated API requests.
const readmeCache = new Map();
function readmeFor(repository) {
  if (!readmeCache.has(repository)) {
    const request = fetch(`https://api.github.com/repos/${repository}/readme`, {
      headers: { Accept: 'application/vnd.github.raw+json' },
      signal: AbortSignal.timeout(15000)
    }).then(response => {
      if (!response.ok) throw new Error(`README unavailable (${response.status})`);
      return response.text();
    }).catch(error => { readmeCache.delete(repository); throw error; });
    readmeCache.set(repository, request);
  }
  return readmeCache.get(repository);
}
async function loadReadme(panel) {
  const repository = panel.dataset.repository;
  const feedback = panel.querySelector('.preview-feedback');
  feedback.textContent = 'Loading README from GitHub...';
  try {
    const text = await readmeFor(repository);
    // README content is untrusted text. Never insert it as HTML.
    const content = element('pre', 'readme-content', text.trim() || 'This README is empty.');
    content.tabIndex = 0;
    content.setAttribute('aria-label', `README for ${repository.split('/')[1]}`);
    feedback.replaceWith(content);
  } catch {
    feedback.textContent = 'README could not be loaded. You can still read it on GitHub.';
    const retry = element('button', 'preview-retry', 'Retry');
    retry.type = 'button';
    retry.addEventListener('click', () => { retry.remove(); loadReadme(panel); });
    feedback.append(retry);
  }
}
const readmeObserver = 'IntersectionObserver' in window ? new IntersectionObserver(entries => {
  for (const entry of entries) {
    if (entry.isIntersecting) { readmeObserver.unobserve(entry.target); loadReadme(entry.target); }
  }
}, { rootMargin: '200px' }) : null;
function createProjectPreview(project) {
  const github = new URL(project.url).hostname === 'github.com';
  const preview = element('div', `project-visual ${github ? 'repository-preview' : 'website-preview'}`);
  if (github) {
    const repository = new URL(project.url).pathname.slice(1);
    preview.dataset.repository = repository;
    const heading = element('a', 'readme-heading', `${repository.split('/')[1]} / README`);
    heading.href = `${project.url}#readme`; heading.target = '_blank'; heading.rel = 'noopener noreferrer';
    preview.append(heading, element('p', 'preview-feedback', 'README from GitHub'));
    if (readmeObserver) readmeObserver.observe(preview); else loadReadme(preview);
  } else {
    const image = element('img', 'website-screenshot');
    image.alt = `Website preview of ${project.title}`;
    image.loading = 'lazy'; image.decoding = 'async';
    // Public URL only. Thum.io captures the destination website, not a fabricated mockup.
    image.src = `https://image.thum.io/get/width/1000/crop/650/noanimate/${project.url}`;
    const feedback = element('p', 'preview-feedback', 'Loading website screenshot...');
    image.addEventListener('load', () => feedback.remove());
    image.addEventListener('error', () => { image.hidden = true; feedback.textContent = 'Website preview unavailable. Use the project link below to visit.'; });
    preview.append(image, feedback, element('span', 'project-status', 'Website preview'));
  }
  return preview;
}
function renderProjects(category = 'All') {
  const visible = projects.filter(project => category === 'All' || project.category === category);
  if (readmeObserver) readmeObserver.disconnect();
  grid.replaceChildren();
  if (!projects.length) {
    const notice = element('p', 'project-empty', 'Public project collection coming soon. Explore my public repositories on GitHub.');
    const profile = element('a', 'text-link', 'View public repositories');
    profile.href = 'https://github.com/LianSianThang?tab=repositories';
    profile.target = '_blank'; profile.rel = 'noopener noreferrer';
    grid.append(notice, profile);
  }
  for (const project of visible) {
    const card = element('article', 'project-card');
    const visual = createProjectPreview(project);
    const heading = element('div','project-title-row'); heading.append(element('h3','',project.title),element('span','project-index',String(projects.indexOf(project)+1).padStart(2,'0')));
    const tech = element('div','tech-list'); project.technologies.forEach(item=>tech.append(element('span','',item)));
    const links = element('div','project-links');
    const link = element('a','',project.url?(project.linkLabel || 'View source'):project.visual==='arena'?'Support this project':'Ask me about this project');
    link.href = project.url || (project.visual==='arena'?'#support-title':'#contact');
    if(project.url){link.target='_blank';link.rel='noopener noreferrer';}
    links.append(link);
    for (const [url, label] of [[project.sourceUrl, 'View repository'], [project.releaseUrl, 'View releases']]) {
      if (!url) continue;
      const extra = element('a', '', label);
      extra.href = url; extra.target = '_blank'; extra.rel = 'noopener noreferrer'; links.append(extra);
    }
    card.append(visual,heading,element('p','',project.description),tech,links); grid.append(card);
  }
  count.textContent=`${visible.length} ${visible.length === 1 ? 'project' : 'projects'}`;
}
